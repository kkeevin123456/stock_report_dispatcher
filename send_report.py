def split_messages(text, max_len=4500):
    messages = []
    current = ''
    for line in text.split('\n'):
        candidate = current + line + '\n'
        if len(candidate) <= max_len:
            current = candidate
        else:
            if current.strip():
                messages.append(current.rstrip())
            current = line + '\n'
    if current.strip():
        messages.append(current.rstrip())
    return messages


